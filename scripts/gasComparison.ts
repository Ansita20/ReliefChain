/**
 * Gas comparison: N separate recordDistribution transactions vs one recordBatch of N.
 *
 * Run with:  npm run gas:compare
 * Writes the result table to docs/gas-comparison.md.
 *
 * Each scenario uses a freshly deployed contract so both approaches start from
 * the same storage state (fair comparison).
 */
import { ethers } from "hardhat";
import { encodeBytes32String } from "ethers";
import * as fs from "fs";
import * as path from "path";
import { computeNullifier, generateCampaignSecret } from "../shared/nullifier";

const FOOD_KIT = encodeBytes32String("FOOD_KIT");
const BATCH_SIZES = [1, 5, 10, 25, 50];

/** Deploy a fresh registry with one active campaign and one approved agency. */
async function freshRegistry() {
  const [admin, agency] = await ethers.getSigners();
  const registry = await ethers.deployContract("ReliefRegistry", [admin.address]);
  const now = (await ethers.provider.getBlock("latest"))!.timestamp;
  await (await registry.createCampaign("Gas test", "Lab", now - 60, now + 86400, [FOOD_KIT])).wait();
  await (await registry.approveAgency(agency.address, "Agency")).wait();
  return registry.connect(agency);
}

/** Make n different beneficiary nullifiers. */
function makeNullifiers(n: number): string[] {
  const secret = generateCampaignSecret();
  return Array.from({ length: n }, (_, i) => computeNullifier(secret, 1n, `ID-${i}`));
}

async function main() {
  const rows: string[] = [];
  console.log("\nGas: single transactions vs one batch\n");

  for (const n of BATCH_SIZES) {
    const nullifiers = makeNullifiers(n);

    // A) n separate transactions
    const singleRegistry = await freshRegistry();
    let singleTotal = 0n;
    for (const nul of nullifiers) {
      const receipt = await (await singleRegistry.recordDistribution(1n, nul, FOOD_KIT)).wait();
      singleTotal += receipt!.gasUsed;
    }

    // B) one batch transaction
    const batchRegistry = await freshRegistry();
    const batchReceipt = await (
      await batchRegistry.recordBatch(1n, nullifiers, Array(n).fill(FOOD_KIT))
    ).wait();
    const batchTotal = batchReceipt!.gasUsed;

    const singlePer = singleTotal / BigInt(n);
    const batchPer = batchTotal / BigInt(n);
    const saving = Number(((singleTotal - batchTotal) * 10000n) / singleTotal) / 100;

    console.log(
      `n=${String(n).padStart(2)}  singles: ${singleTotal} gas (${singlePer}/record)   ` +
        `batch: ${batchTotal} gas (${batchPer}/record)   saving: ${saving}%`,
    );
    rows.push(`| ${n} | ${singleTotal} | ${singlePer} | ${batchTotal} | ${batchPer} | ${saving}% |`);
  }

  const markdown = [
    "# Gas comparison: single records vs batch",
    "",
    "Generated by `npm run gas:compare` on the in-process Hardhat network (Solidity optimizer on, 200 runs).",
    "Each row starts from a freshly deployed contract so both approaches pay the same storage costs.",
    "",
    "| Records (n) | n × recordDistribution (total gas) | per record | 1 × recordBatch (total gas) | per record | Saving |",
    "|---:|---:|---:|---:|---:|---:|",
    ...rows,
    "",
    "**Why the batch is cheaper:** every Ethereum transaction pays a fixed 21,000 gas base fee,",
    "plus the role check and campaign checks. A batch pays these once instead of n times, and",
    "after the first record the per-campaign counters are already warm in storage.",
    "",
    "**When not to batch:** for a single record, `recordBatch` costs slightly more than",
    "`recordDistribution` because of the extra array encoding. Batching pays off from 2+ records.",
    "",
  ].join("\n");

  const outFile = path.join(__dirname, "..", "docs", "gas-comparison.md");
  fs.mkdirSync(path.dirname(outFile), { recursive: true });
  fs.writeFileSync(outFile, markdown);
  console.log(`\nWritten to ${path.relative(process.cwd(), outFile)}`);
}

main().catch((err) => {
  console.error(err);
  process.exitCode = 1;
});
